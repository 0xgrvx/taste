# Generate SVG with diagonal hatch lines
# Usage: gen_hatch <width> <height> <bg_color> <line_color> <line_width>
gen_hatch() {
  local w="$1" h="$2" bg="$3" lc="$4" lw="$5" step="$6"
  local svg="<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"$w\" height=\"$h\">"
  svg+="<rect width=\"$w\" height=\"$h\" fill=\"$bg\" rx=\"4\"/>"
  svg+="<g stroke=\"$lc\" stroke-width=\"$lw\">"
  local diag=$((w > h ? w : h))
  local i
  for ((i = -diag; i <= diag * 2; i += step)); do
    svg+="<line x1=\"$i\" y1=\"0\" x2=\"$((i + step))\" y2=\"$step\"/>"
  done
  svg+="</g></svg>"
  echo "$svg"
}

