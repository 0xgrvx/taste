import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')

const registryDir = path.join(root, 'registry')
const entriesDir = path.join(registryDir, 'entries')
const outFile = path.join(root, 'lib', 'registry-data.ts')

// Read categories
const categoriesPath = path.join(registryDir, 'categories.json')
if (!existsSync(categoriesPath)) {
  console.error('Missing registry/categories.json')
  process.exit(1)
}
const CATEGORIES = JSON.parse(readFileSync(categoriesPath, 'utf-8'))

// Read all entries
if (!existsSync(entriesDir)) {
  console.error('Missing registry/entries/ directory')
  process.exit(1)
}

const entryFiles = readdirSync(entriesDir)
  .filter((f) => f.endsWith('.json'))
  .sort()

const ENTRIES = entryFiles.map((f) => {
  const content = readFileSync(path.join(entriesDir, f), 'utf-8')
  return JSON.parse(content)
})

// Generate TypeScript
const ts = `// Auto-generated by scripts/build-registry.mjs — do not edit directly
// Source: registry/entries/*.json and registry/categories.json

export const CATEGORIES = ${JSON.stringify(CATEGORIES, null, 2)} as const

export const ENTRIES = ${JSON.stringify(ENTRIES, null, 2)} as const
`

writeFileSync(outFile, ts, 'utf-8')
console.log(`✓ Built lib/registry-data.ts: ${CATEGORIES.length} categories, ${ENTRIES.length} entries`)
